function mk(s: Seed, level: WordLevel): Word {
  return {
    id: `word.${s.w.replace(/\s+/g, '_')}`,
    word: s.w,
    phonetic: s.p,
    partOfSpeech: s.pos,
    coreMeaning: s.m,
    examMeanings: [],
    level,
    frequencyScore: 0,
    phrases: [],
    collocations: s.coll ?? [],
    synonyms: s.syn ?? [],
    antonyms: [],
    confusingWords: s.conf ?? [],
    wordFamily: [],
    exampleSentence: s.ex ? { en: s.ex[0], zh: s.ex[1] } : null,
    source: 'manual' as SourceKind,
    examYears: [],
  };
}

